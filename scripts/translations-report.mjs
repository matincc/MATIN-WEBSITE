// Generates TRANSLATIONS_FOR_REVIEW.md: every interface string that has a French or
// Persian translation written for the site (not supplied by Matin), next to its English
// source, plus the Persian text stored in content files.
// Usage: node scripts/translations-report.mjs
import { readFile, writeFile } from 'node:fs/promises';
import fr from '../src/i18n/fr.ts';
import en from '../src/i18n/en.ts';
import fa, { faFallbackNotice } from '../src/i18n/fa.ts';

// French copy supplied verbatim in the brief (not a translation to review).
const frSupplied = new Set([
  'home.heroEyebrow',
  'home.heroTitle',
  'home.heroLine1',
  'home.heroLine2',
  'home.whoTitle',
  'home.whoText',
  'brand.tagline',
  'brand.secondaryTagline',
  'meta.siteName',
]);
// French written for this update (sections 5–12 of the brief).
const frNewSections = ['home', 'newsletter', 'interest', 'newsCategories', 'involved'];
const frNewKeys = new Set([
  'nav.whoWeAre',
  'nav.mission',
  'nav.vision',
  'nav.values',
  'nav.eventsArchive',
  'a11y.aboutSubmenu',
  'about.whoWeAre',
  'events.archiveTitle',
  'events.archiveLede',
  'events.archiveEmpty',
  'events.viewArchive',
  'events.report',
  'events.highlights',
  'events.photos',
  'news.lede',
  'news.source',
  'news.sourceIntro',
  'meta.defaultDescription',
  'meta.homeTitle',
]);

const flatten = (obj, prefix = '') =>
  Object.entries(obj).flatMap(([k, v]) =>
    typeof v === 'string' ? [[prefix + k, v]] : flatten(v, `${prefix}${k}.`),
  );
const get = (obj, key) => key.split('.').reduce((o, p) => o?.[p], obj);
const cell = (s) => (s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

const frRows = flatten(fr)
  .map(([key]) => key)
  .filter((key) => frNewSections.includes(key.split('.')[0]) || frNewKeys.has(key))
  .map((key) => ({
    key,
    en: get(en, key),
    fr: get(fr, key),
    note: frSupplied.has(key) ? 'supplied' : 'to review',
  }));

const faRows = flatten(fa).map(([key, value]) => ({ key, en: get(en, key), fa: value }));

// Persian stored in content files (mission, vision, values).
const content = [];
for (const file of ['src/content/settings/site.yaml', 'src/content/about/about.yaml']) {
  const text = await readFile(file, 'utf8');
  const lines = text.split('\n');
  lines.forEach((line, i) => {
    const m = line.match(/^(\s*)fa: "(.*)"\s*$/) ?? line.match(/fa: "([^"]*)" \}/);
    if (!m) return;
    const faText = m[2] ?? m[1];
    // English is on the previous line (block style) or in the same inline object.
    const inlineEn = line.match(/en: "([^"]*)"/);
    const prevEn = lines[i - 1]?.match(/en: "(.*)"\s*$/);
    content.push({ file, en: inlineEn?.[1] ?? prevEn?.[1] ?? '', fa: faText });
  });
}

const out = [];
out.push('# Translations for review · Traductions à réviser · ترجمه‌ها برای بازبینی');
out.push('');
out.push(
  'Generated by `node scripts/translations-report.mjs` from the site’s translation files. ' +
    'Edit the texts in `src/i18n/fr.ts`, `src/i18n/fa.ts` and the content files, then regenerate this file.',
);
out.push('');
out.push('- **supplied**: copy given in the brief, used verbatim (no review needed).');
out.push(
  '- **to review**: written for the site; please have a fluent speaker check it before launch.',
);
out.push(
  '- French typography follows Québec (OQLF) rules automatically: no space before `?` `!` `;`, ' +
    'non-breaking space before `:` and inside « ».',
);
out.push('');
out.push(`## 1. French (${frRows.filter((r) => r.note === 'to review').length} strings to review)`);
out.push('');
out.push('| Key | English (source) | Français | Status |');
out.push('| --- | --- | --- | --- |');
for (const r of frRows) out.push(`| \`${r.key}\` | ${cell(r.en)} | ${cell(r.fr)} | ${r.note} |`);
out.push('');
out.push(`## 2. Persian — interface (${faRows.length} strings, all to review)`);
out.push('');
out.push(
  'Persian is an additional access language. Pages without a Persian version open in English with a short note.',
);
out.push('');
out.push('| Key | English (source) | فارسی |');
out.push('| --- | --- | --- |');
for (const r of faRows) out.push(`| \`${r.key}\` | ${cell(r.en)} | ${cell(r.fa)} |`);
out.push('');
out.push('## 3. Persian — notices');
out.push('');
out.push('| Where | English meaning | فارسی |');
out.push('| --- | --- | --- |');
out.push(
  `| French/English page opened from the Persian site | This page is not available in Persian yet and is shown in English. | ${cell(faFallbackNotice.text)} |`,
);
out.push(`| Same notice, link | Back to the Persian home page | ${cell(faFallbackNotice.back)} |`);
out.push(
  '| Language switcher (description for screen readers) | Read this page in Persian / Go to the Persian site | این صفحه را به فارسی بخوانید / رفتن به نسخه فارسی سایت |',
);
out.push('');
out.push(`## 4. Persian — content files (${content.length} texts, all to review)`);
out.push('');
out.push(
  'Mission and vision have no Persian translation yet: the Persian About page shows the values only until they are translated.',
);
out.push('');
out.push('| File | English (source) | فارسی |');
out.push('| --- | --- | --- |');
for (const r of content) out.push(`| \`${r.file}\` | ${cell(r.en)} | ${cell(r.fa)} |`);
out.push('');

await writeFile('TRANSLATIONS_FOR_REVIEW.md', out.join('\n'));
console.log(
  `French rows: ${frRows.length} · Persian UI: ${faRows.length} · Persian content: ${content.length}`,
);
