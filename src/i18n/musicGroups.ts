const dicts: Record<UiLang, MusicDict> = { fr, en, fa };

export function musicStrings(lang: UiLang): MusicDict {
  const d = dicts[lang] ?? dicts.en;
  return Object.fromEntries(Object.entries(d).map(([k, v]) => [k, typo(v, lang)])) as MusicDict;
}
